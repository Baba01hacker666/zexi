// Package bindgen generates Zexi `extern "C"` declarations from a C
// header file. It understands the common, portable subset of C —
// scalar types, `char *` strings, opaque pointers, sized integers — and
// politely skips what it cannot map (variadic functions, function
// pointers, by-value structs), listing every skip in the output so a
// human can finish the job by hand.
//
// The generated declarations are only half of the C bridge: link the
// implementation with `zexic build app.zx --csrc=glue.c --link=m`.
package bindgen

import (
	"fmt"
	"strings"
)

// Result is the outcome of generating bindings for one header.
type Result struct {
	// Source is the generated Zexi source.
	Source string
	// Bound lists the C functions that were translated.
	Bound []string
	// Skipped lists "name (reason)" for declarations left out.
	Skipped []string
}

// scalarTypes maps normalized C scalar spellings to Zexi types.
var scalarTypes = map[string]string{
	"void":               "",
	"char":               "i8",
	"signed char":        "i8",
	"unsigned char":      "u8",
	"short":              "i16",
	"short int":          "i16",
	"unsigned short":     "u16",
	"int":                "i32",
	"unsigned":           "u32",
	"unsigned int":       "u32",
	"long":               "i64",
	"long int":           "i64",
	"unsigned long":      "u64",
	"long long":          "i64",
	"unsigned long long": "u64",
	"size_t":             "usize",
	"ssize_t":            "isize",
	"ptrdiff_t":          "isize",
	"intptr_t":           "isize",
	"uintptr_t":          "usize",
	"float":              "f32",
	"double":             "f64",
	"bool":               "bool",
	"_Bool":              "bool",
	"int8_t":             "i8",
	"int16_t":            "i16",
	"int32_t":            "i32",
	"int64_t":            "i64",
	"uint8_t":            "u8",
	"uint16_t":           "u16",
	"uint32_t":           "u32",
	"uint64_t":           "u64",
}

// typeWords are C words that can appear in a bare (unnamed) parameter
// type such as `unsigned long`.
var typeWords = map[string]bool{
	"void": true, "char": true, "short": true, "int": true, "long": true,
	"float": true, "double": true, "signed": true, "unsigned": true,
	"const": true, "size_t": true, "ssize_t": true, "bool": true,
}

// Generate translates C header source into Zexi extern declarations.
// headerName is used only for the generated file's banner comment.
func Generate(src []byte, headerName string) Result {
	text := stripComments(string(src))
	text = strings.ReplaceAll(text, `extern "C" {`, " ")
	text = strings.ReplaceAll(text, `extern "C"`, " ")

	var r Result
	var decls []string
	for _, stmt := range strings.Split(text, ";") {
		stmt = strings.TrimSpace(stmt)
		if stmt == "" {
			continue
		}
		if strings.Contains(stmt, "#") {
			// A preprocessor line glued to a declaration: drop lines.
			var kept []string
			for _, ln := range strings.Split(stmt, "\n") {
				if !strings.HasPrefix(strings.TrimSpace(ln), "#") {
					kept = append(kept, ln)
				}
			}
			stmt = strings.TrimSpace(strings.Join(kept, "\n"))
			if stmt == "" {
				continue
			}
		}
		decl, name, reason := translate(stmt)
		switch {
		case decl != "":
			decls = append(decls, decl)
			r.Bound = append(r.Bound, name)
		case reason != "":
			r.Skipped = append(r.Skipped, reason)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by `zexic bindgen %s`; DO NOT EDIT.\n", headerName)
	b.WriteString("// Regenerate with: zexic bindgen " + headerName + "\n")
	b.WriteString("// Link the C side with: zexic build app.zx --csrc=<impl>.c --link=<lib>\n")
	if len(r.Skipped) > 0 {
		b.WriteString("//\n// Not translated (write these declarations by hand if you need them):\n")
		for _, s := range r.Skipped {
			b.WriteString("//   " + s + "\n")
		}
	}
	b.WriteString("\n")
	b.WriteString(strings.Join(decls, "\n"))
	if len(decls) > 0 {
		b.WriteString("\n")
	}
	r.Source = b.String()
	return r
}

// translate converts one `;`-terminated declaration chunk into a Zexi
// extern declaration. It returns ("", "", reason) for declarations that
// are skipped, and ("", "", "") for chunks that are not declarations at
// all (typedefs, struct bodies, stray braces, ...).
func translate(stmt string) (decl, name, skipReason string) {
	for _, kw := range []string{"typedef", "struct", "enum", "union"} {
		if hasWordPrefix(stmt, kw) {
			return "", "", ""
		}
	}
	if strings.Contains(stmt, "{") || strings.Contains(stmt, "}") {
		return "", "", "" // a definition or an aggregate body
	}
	open := strings.Index(stmt, "(")
	if open < 0 {
		return "", "", ""
	}
	closeIdx := strings.LastIndex(stmt, ")")
	if closeIdx < open {
		return "", "", ""
	}
	prefix := strings.TrimSpace(stmt[:open])
	paramsText := stmt[open+1 : closeIdx]

	// The function name is the last identifier of the prefix; everything
	// before it is the return type.
	i := len(prefix)
	for i > 0 && isIdentByte(prefix[i-1]) {
		i--
	}
	if i == len(prefix) {
		return "", "", ""
	}
	name = prefix[i:]
	retText := strings.TrimSpace(prefix[:i])
	if strings.HasPrefix(retText, "static") {
		return "", "", name + " (static: internal to the C file)"
	}
	retText = strings.TrimPrefix(retText, "extern")
	retText = strings.TrimSpace(retText)
	if strings.Contains(retText, "struct") || strings.Contains(retText, "enum") || strings.Contains(retText, "union") {
		return "", "", name + " (aggregate return type)"
	}
	ret, ok := mapType(retText, true)
	if !ok {
		return "", "", fmt.Sprintf("%s (unsupported return type `%s`)", name, normalize(retText))
	}

	var params []string
	paramsText = strings.TrimSpace(paramsText)
	if paramsText != "" && paramsText != "void" {
		for j, raw := range strings.Split(paramsText, ",") {
			raw = strings.TrimSpace(raw)
			if raw == "..." {
				return "", "", name + " (variadic)"
			}
			if strings.Contains(raw, "(") {
				return "", "", name + " (function-pointer parameter)"
			}
			pname, pty, pok := translateParam(raw, j)
			if !pok {
				return "", "", fmt.Sprintf("%s (unsupported parameter `%s`)", name, normalize(raw))
			}
			params = append(params, pname+": "+pty)
		}
	}

	var b strings.Builder
	b.WriteString("extern \"C\" fn " + name + "(" + strings.Join(params, ", ") + ")")
	if ret != "" {
		b.WriteString(" -> " + ret)
	}
	b.WriteString(";")
	return b.String(), name, ""
}

// translateParam maps one C parameter to a Zexi "name: type" pair.
func translateParam(raw string, idx int) (string, string, bool) {
	// Array parameters decay to pointers: `char buf[64]` is `char *buf`.
	isArray := false
	if lb := strings.Index(raw, "["); lb >= 0 {
		isArray = true
		raw = strings.TrimSpace(raw[:lb])
	}
	// Split off the trailing parameter name, if any.
	name := ""
	rest := raw
	if i := len(raw); i > 0 {
		j := i
		for j > 0 && isIdentByte(raw[j-1]) {
			j--
		}
		cand := raw[j:]
		before := strings.TrimSpace(raw[:j])
		// The candidate is a name only when what precedes it is a type:
		// a bare type (`unsigned long`) must not lose its last word.
		if cand != "" && before != "" && !isBareType(raw) {
			name = cand
			rest = before
		}
	}
	if name == "" {
		name = fmt.Sprintf("a%d", idx)
	}
	ty, ok := mapType(rest, false)
	if !ok {
		return "", "", false
	}
	if isArray {
		// `T name[N]` arrives in Zexi as a pointer to the element type.
		// A char array is a byte buffer, matching `char *` -> `*mut u8`.
		if ty == "i8" {
			ty = "*mut u8"
		} else if !strings.HasPrefix(ty, "*") && ty != "str" {
			ty = "*mut " + ty
		}
	}
	return name, ty, true
}

// isBareType reports whether raw is only a type (an unnamed parameter).
func isBareType(raw string) bool {
	for _, w := range strings.Fields(strings.ReplaceAll(raw, "*", " * ")) {
		if w == "*" {
			continue
		}
		if !typeWords[w] {
			return false
		}
	}
	return true
}

// mapType maps a C type spelling to a Zexi type. isReturn selects the
// return-position treatment of `void`.
func mapType(text string, isReturn bool) (string, bool) {
	norm := normalize(text)
	isConst := false
	var words []string
	for _, w := range strings.Fields(norm) {
		if w == "const" {
			isConst = true
			continue
		}
		words = append(words, w)
	}
	joined := strings.Join(words, " ")
	stars := strings.Count(joined, "*")
	base := strings.TrimSpace(strings.ReplaceAll(joined, "*", ""))
	base = strings.Join(strings.Fields(base), " ")

	if stars == 0 {
		zx, ok := scalarTypes[base]
		if !ok || (zx == "" && !isReturn) {
			return "", false
		}
		return zx, true
	}
	if stars > 1 {
		return "", false
	}
	// A single pointer.
	switch base {
	case "char":
		if isConst {
			return "str", true
		}
		return "*mut u8", true
	case "void":
		if isConst {
			return "*u8", true
		}
		return "*mut u8", true
	}
	elem, ok := scalarTypes[base]
	if !ok || elem == "" {
		return "", false
	}
	if isConst {
		return "*" + elem, true
	}
	return "*mut " + elem, true
}

// normalize collapses all whitespace runs to single spaces.
func normalize(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func hasWordPrefix(s, kw string) bool {
	if !strings.HasPrefix(s, kw) {
		return false
	}
	rest := s[len(kw):]
	return rest == "" || !isIdentByte(rest[0])
}

func isIdentByte(c byte) bool {
	return c == '_' || (c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
}

// stripComments removes /* */ and // comments.
func stripComments(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); {
		if i+1 < len(s) && s[i] == '/' && s[i+1] == '*' {
			end := strings.Index(s[i+2:], "*/")
			if end < 0 {
				break
			}
			i += 2 + end + 2
			b.WriteByte(' ')
			continue
		}
		if i+1 < len(s) && s[i] == '/' && s[i+1] == '/' {
			end := strings.IndexByte(s[i:], '\n')
			if end < 0 {
				break
			}
			i += end
			continue
		}
		b.WriteByte(s[i])
		i++
	}
	return b.String()
}
