// Package llvm is Zexi's experimental LLVM-IR backend. It consumes the MIR
// program (`internal/mir`) — the same backend contract docs/04 §4.3 fixes —
// and emits LLVM IR text, which a clang/llc toolchain turns into a native
// binary. It is the swappable-native-backend step of docs/06 §6.4, built
// behind the C backend as the reference implementation.
//
// Scope: LLVM IR is emitted for the language subset MIR supports (the
// computational core plus the String/interpolation runtime intrinsics).
// Wherever it can, this backend reproduces exactly what the C backend does at
// OptLevel 2 (-fwrapv): signed integer arithmetic wraps, integer division by
// zero panics with the same exit code, INT_MIN/-1 panics instead of trapping,
// remainders by -1 are zero, and drops are guarded by the same drop flags.
// With DebugChecks (OptLevel 0), add/sub/mul also panic on overflow via the
// llvm.*with.overflow intrinsics, matching the checked C helpers. Anything
// outside that subset is reported, never silently miscompiled.
//
// # Type representation
//
// Types and value sizes come only from the layout table (`internal/layout`):
//
//   - scalars map to LLVM integer/float types of the same width;
//   - `str`, `ptr`, and `&T` are the opaque `ptr` type, matching the C
//     runtime's borrowed `const char*`;
//   - String/Vec/HashMap handles share one `{ ptr, i64, i64 }` type
//     (`zx_String` in the C shim), slices the `{ ptr, i64 }` fat pointer;
//   - structs become named LLVM types whose members are separated and
//     followed by explicit `[N x i8]` padding members, so LLVM's natural
//     layout reproduces the table's offsets field by field;
//   - enums are `[Size x i8]` byte records addressed through the table's
//     tag, payload, and variant-field offsets.
//
// Because every aggregate's LLVM representation is exactly its layout size,
// composite members land where the table says without LLVM having to guess,
// and a move of a value is a plain load/store byte copy.
package llvm

import (
	"fmt"
	"strings"

	"zexi/internal/layout"
	"zexi/internal/mir"
	"zexi/internal/types"
)

// Options configures LLVM emission.
type Options struct {
	// DebugChecks enables the release-elided overflow checks on + - * that a
	// debug C build gets. Division checks are emitted unconditionally: the C
	// backend panics on division by zero in every profile, and LLVM would
	// trap on INT_MIN / -1 even under wrap semantics.
	DebugChecks bool
}

// UnsupportedError reports a construct this backend does not lower. The C
// backend is the reference; rather than emit wrong machine code, the LLVM
// backend refuses the function.
type UnsupportedError struct{ What string }

func (e *UnsupportedError) Error() string { return "llvm backend: " + e.What }

func unsupportedf(format string, args ...any) error {
	return &UnsupportedError{What: fmt.Sprintf(format, args...)}
}

// handleType is the shared owning-handle shape `{ ptr, i64, i64 }`: the C
// runtime's `zx_String`, `zx_vec_<T>`, and `zx_hashmap_<K>_<V>` all have
// exactly these size and alignment (see the handle row of internal/layout).
const handleType = "%zx.Handle"

// sliceType is the `{ ptr, i64 }` two-word borrowed slice view.
const sliceType = "%zx.Slice"

// Generate emits prog as one LLVM IR module. The returned text plus ShimC
// compile and link into a native binary with clang (see internal/driver).
func Generate(prog *mir.Program, opts Options) (string, error) {
	if prog == nil {
		return "", unsupportedf("nil program")
	}
	if prog.Main == nil {
		return "", unsupportedf("program has no main")
	}
	m := &module{
		prog:         prog,
		opts:         opts,
		tgt:          layout.Default(),
		strs:         map[string]string{},
		structTypes:  map[*types.Struct]string{},
		structLayout: map[string]layout.Struct{},
		enumLayout:   map[string]layout.Enum{},
		memberIdx:    map[string][]int{},
		declared:     map[string]bool{},
		writtenTypes: map[string]bool{},
	}
	fmt.Fprintf(&m.w, `; ModuleID = 'zexi'
; Generated by the Zexi LLVM backend from MIR (zexic emit --emit=llvm).
; Runtime intrinsics are provided by the C shim in internal/codegen/llvm;
; inline c-blocks are not part of the LLVM pipeline in this phase.
source_filename = "zexic"

; The shared handle and slice shapes (see the handle row of internal/layout).
%%zx.Handle = type { ptr, i64, i64 }
%%zx.Slice = type { ptr, i64 }
`)
	if err := m.collectTypes(); err != nil {
		return "", err
	}
	if err := m.emitFns(); err != nil {
		return "", err
	}
	m.w.WriteString("\n; --- string literal globals (collected during emission) ---\n")
	for _, g := range m.strOrder {
		m.w.WriteString(g)
		m.w.WriteString("\n")
	}
	return m.w.String(), nil
}

type module struct {
	prog *mir.Program
	opts Options
	// w holds declarations and function definitions, in emission order.
	w strings.Builder
	// tail holds string-literal globals discovered while emitting: LLVM does
	// not care that they are defined after their uses in the text.
	tail strings.Builder

	tgt layout.Target

	// strs deduplicates string literals; the value is the global symbol.
	strs        map[string]string
	strOrder    []string
	nextLiteral int

	// structTypes names a checked struct declaration's LLVM type.
	structTypes map[*types.Struct]string
	// structLayout and enumLayout cache layout table rows by name.
	structLayout map[string]layout.Struct
	enumLayout   map[string]layout.Enum
	// memberIdx maps a struct declaration name to the LLVM member index of
	// each declared field (explicit padding members shift the indexes).
	memberIdx map[string][]int
	// writtenTypes records named type definitions already emitted.
	writtenTypes map[string]bool
	// declared records intrinsic declarations already emitted.
	declared map[string]bool
}

// collectTypes pre-builds the layout rows for the program's struct and enum
// declarations, in declaration order, so no later lookup depends on order.
func (m *module) collectTypes() error {
	for _, st := range m.prog.Structs {
		if st == nil || st.Generic {
			continue
		}
		lo, err := m.tgt.Struct(st)
		if err != nil {
			return fmt.Errorf("layout of struct %s: %w", st.Name, err)
		}
		m.structLayout[st.Name] = lo
		if err := m.declareStructType(st); err != nil {
			return err
		}
	}
	for _, en := range m.prog.Enums {
		if en == nil || en.Generic {
			continue
		}
		lo, err := m.tgt.Enum(en)
		if err != nil {
			return fmt.Errorf("layout of enum %s: %w", en.Name, err)
		}
		m.enumLayout[en.Name] = lo
	}
	return nil
}

// declareStructType emits `%"st.name" = type { ... }` with explicit padding
// members reproducing the layout table's offsets exactly, and records each
// declared field's LLVM member index for later field projections.
func (m *module) declareStructType(st *types.Struct) error {
	if st == nil {
		return unsupportedf("struct type without a definition")
	}
	if st.Generic {
		return unsupportedf("generic struct %s was not instantiated", st.Name)
	}
	if _, done := m.writtenTypes[st.Name]; done {
		return nil
	}
	m.writtenTypes[st.Name] = true

	lo, ok := m.structLayout[st.Name]
	if !ok {
		var err error
		if lo, err = m.tgt.Struct(st); err != nil {
			return err
		}
		m.structLayout[st.Name] = lo
	}
	var members []string
	idx := make([]int, len(lo.Fields))
	cur := int64(0)
	for j, f := range st.Fields {
		// Zero-sized fields (unit, never, empty tuples) hold no storage and
		// have no LLVM member; -1 marks them so address formation can reject
		// any attempt to reach them.
		if f.Ty != nil && (f.Ty.Kind == types.Unit || f.Ty.Kind == types.Never) {
			idx[j] = -1
			continue
		}
		fel, err := m.llTy(f.Ty)
		if err != nil {
			return fmt.Errorf("struct %s field %s: %w", st.Name, f.Name, err)
		}
		if gap := lo.Fields[j].Offset - cur; gap > 0 {
			members = append(members, fmt.Sprintf("[%d x i8]", gap))
		}
		members = append(members, fel)
		idx[j] = len(members) - 1
		cur = lo.Fields[j].Offset + lo.Fields[j].Sized.Size
	}
	if tail := lo.Size - cur; tail > 0 {
		members = append(members, fmt.Sprintf("[%d x i8]", tail))
	}
	name := structTypeName(st.Name)
	fmt.Fprintf(&m.w, "%s = type { %s }\n", name, strings.Join(members, ", "))
	m.memberIdx[st.Name] = idx
	return nil
}

// llTy maps a checked Zexi type to its LLVM type string.
func (m *module) llTy(ty *types.Type) (string, error) {
	if ty == nil {
		return "", unsupportedf("nil type")
	}
	switch ty.Kind {
	case types.Bool:
		return "i1", nil
	case types.I8, types.U8:
		return "i8", nil
	case types.I16, types.U16:
		return "i16", nil
	case types.I32, types.U32, types.Char:
		return "i32", nil
	case types.I64, types.U64, types.Isize, types.Usize:
		return "i64", nil
	case types.F32:
		return "float", nil
	case types.F64:
		return "double", nil
	case types.Str, types.Ptr, types.Ref, types.Fn:
		// Opaque point: a uniform word, matching the C runtime's borrowed
		// `const char*` and function values.
		return "ptr", nil
	case types.StringKind, types.VecKind, types.MapKind:
		return handleType, nil
	case types.Slice:
		return sliceType, nil
	case types.Array:
		if ty.Elem == nil || ty.Len < 0 {
			return "", unsupportedf("array type %s without a shape", ty)
		}
		elem, err := m.llTy(ty.Elem)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("[%d x %s]", ty.Len, elem), nil
	case types.StructKind:
		if ty.St == nil {
			return "", unsupportedf("struct type without a definition")
		}
		if _, ok := m.structTypes[ty.St]; !ok {
			if err := m.declareStructType(ty.St); err != nil {
				return "", err
			}
			m.structTypes[ty.St] = structTypeName(ty.St.Name)
		}
		return m.structTypes[ty.St], nil
	case types.EnumKind:
		lo, err := m.enumOf(ty.En)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("[%d x i8]", lo.Size), nil
	default:
		return "", unsupportedf("type %s has no LLVM representation", ty)
	}
}

func (m *module) enumOf(en *types.Enum) (layout.Enum, error) {
	if en == nil {
		return layout.Enum{}, unsupportedf("enum type without a definition")
	}
	if lo, ok := m.enumLayout[en.Name]; ok {
		return lo, nil
	}
	lo, err := m.tgt.Enum(en)
	if err != nil {
		return layout.Enum{}, err
	}
	m.enumLayout[en.Name] = lo
	return lo, nil
}

func structTypeName(name string) string { return "%st." + llIdent(name) }

// llIdent renders an LLVM identifier: bare when the text is a plain iA-Z
// identifier, quoted (with `$` escaped) otherwise, because Zexi types and
// function names contain characters like `:` and `$`.
func llIdent(name string) string {
	if plainIdent(name) {
		return name
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range name {
		switch r {
		case '\\', '"', '$':
			fmt.Fprintf(&b, "\\%02x", r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func plainIdent(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if !(r == '_' || r == '.' ||
			(r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')) {
			return false
		}
	}
	return true
}

// llName renders an LLVM symbol (@name), quoting as needed.
func llName(name string) string { return "@" + llIdent(name) }

// declareIntrinsic records one declaration line (already spelled with its
// `declare` keyword) for a shim helper or intrinsic, once.
func (m *module) declareIntrinsic(sig string) {
	if m.declared[sig] {
		return
	}
	m.declared[sig] = true
	fmt.Fprintf(&m.w, "%s\n", sig)
}

// strSymbol returns the LLVM global holding a NUL-terminated copy of text.
func (m *module) strSymbol(text string) string {
	if sym, ok := m.strs[text]; ok {
		return sym
	}
	name := fmt.Sprintf("@.str.%d", m.nextLiteral)
	m.nextLiteral++
	n := len(text)
	var b strings.Builder
	fmt.Fprintf(&b, "%s = private unnamed_addr constant [%d x i8] c\"", name, n+1)
	for i := 0; i < n; i++ {
		c := text[i]
		if c >= 0x20 && c <= 0x7e && c != '"' && c != '\\' {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "\\%02X", c)
		}
	}
	b.WriteString("\\00")
	b.WriteByte('"')
	m.strs[text] = name
	m.strOrder = append(m.strOrder, b.String())
	return name
}

// strCon returns the operand value for a borrowed string literal: a pointer
// to its first byte (matching the C backend's `const char*` str).
func (m *module) strCon(text string) string {
	sym := m.strSymbol(text)
	n := len(text) + 1
	// As a value, a GEP constantexpr parenthesizes its operand list.
	return fmt.Sprintf("getelementptr inbounds ([%d x i8], ptr %s, i64 0, i64 0)", n, sym)
}

// emitFns lowers every reachable function body; extern "C" declarations are
// skipped (bodies are nil) and only appear through unsupported call paths.
func (m *module) emitFns() error {
	for _, fn := range m.prog.Fns {
		if fn == nil || fn.Body == nil {
			continue
		}
		if err := m.emitFn(fn); err != nil {
			return err
		}
	}
	return nil
}
